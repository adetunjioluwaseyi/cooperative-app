export function formatNaira(amount: number): string {
  const abs = Math.abs(Math.round(amount));
  return `${amount < 0 ? '-' : ''}₦${abs.toLocaleString('en-NG')}`;
}

export function formatShortDate(isoDate: string): string {
  if (!isoDate) return '—';
  const d = new Date(isoDate + (isoDate.length === 10 ? 'T00:00:00' : ''));
  if (isNaN(d.getTime())) return isoDate;
  return d.toLocaleDateString('en-NG', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

export function formatCompactDate(isoDate: string): string {
  if (!isoDate) return '—';
  const d = new Date(isoDate + (isoDate.length === 10 ? 'T00:00:00' : ''));
  if (isNaN(d.getTime())) return isoDate;
  return d.toLocaleDateString('en-NG', {
    month: 'short',
    day: 'numeric',
  });
}

export function normalizePhone(raw: string): string {
  const digits = raw.replace(/\D/g, '');
  if (digits.startsWith('234') && digits.length >= 13) {
    return `+${digits.slice(0, 3)} ${digits.slice(3, 6)} ${digits.slice(6, 9)} ${digits.slice(9, 13)}`;
  }
  if (digits.startsWith('0') && digits.length >= 11) {
    return `+234 ${digits.slice(1, 4)} ${digits.slice(4, 7)} ${digits.slice(7, 11)}`;
  }
  return raw.trim();
}

export function phonesMatch(a: string, b: string): boolean {
  const clean = (s: string) => {
    const d = s.replace(/\D/g, '');
    if (d.startsWith('234')) return d.slice(3);
    if (d.startsWith('0')) return d.slice(1);
    return d;
  };
  const ca = clean(a);
  const cb = clean(b);
  return ca.length >= 10 && ca === cb;
}

export function getMembershipMonths(membershipDate: string, referenceDate = new Date('2026-11-24')): number {
  const start = new Date(membershipDate + 'T00:00:00');
  if (isNaN(start.getTime())) return 0;
  const years = referenceDate.getFullYear() - start.getFullYear();
  const months = referenceDate.getMonth() - start.getMonth();
  const dayAdjust = referenceDate.getDate() >= start.getDate() ? 0 : -1;
  return Math.max(0, years * 12 + months + dayAdjust);
}

export function formatMembershipDuration(membershipDate: string): string {
  const totalMonths = getMembershipMonths(membershipDate);
  if (totalMonths < 1) return 'Less than 1 month';
  if (totalMonths < 12) return `${totalMonths} ${totalMonths === 1 ? 'month' : 'months'}`;
  const years = Math.floor(totalMonths / 12);
  const rem = totalMonths % 12;
  if (rem === 0) return `${years} ${years === 1 ? 'year' : 'years'}`;
  return `${years} ${years === 1 ? 'year' : 'years'}, ${rem} ${rem === 1 ? 'month' : 'months'}`;
}

export function buildReducingBalanceSchedule(
  originalAmount: number,
  months: number,
  paymentsMade: number,
  startIsoDate: string,
  monthlyRatePercent = 1
): LoanRepaymentRow[] {
  const principalPerMonth = Math.round(originalAmount / months);
  const rows: LoanRepaymentRow[] = [];
  let runningBalance = originalAmount;
  const start = new Date(startIsoDate + 'T00:00:00');

  for (let m = 1; m <= months; m++) {
    const interest = Math.round(runningBalance * (monthlyRatePercent / 100));
    const principal = m === months ? runningBalance : Math.min(principalPerMonth, runningBalance);
    const totalPayment = principal + interest;
    runningBalance = Math.max(0, runningBalance - principal);

    const dueDate = new Date(start);
    dueDate.setMonth(start.getMonth() + m);
    const iso = dueDate.toISOString().slice(0, 10);

    let status: LoanRepaymentRow['status'] = 'Upcoming';
    if (m <= paymentsMade) status = 'Paid';
    else if (m === paymentsMade + 1) status = 'Due Soon';

    rows.push({
      month: m,
      date: iso,
      amountPaid: totalPayment,
      principal,
      interest,
      remainingBalance: runningBalance,
      status,
    });
  }
  return rows;
}

